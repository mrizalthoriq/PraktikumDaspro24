public class ContohVariable24 {
    public static void main(String[] args) {
        
        String hobiSaya = "Bersepeda";
        boolean isPandai = true;
        char kelamin = 'L'; 
        byte umurSaatIni = 19;
        double $ipk = 3.67, tinggi = 167;

        System.out.println(hobiSaya);
        System.out.println("Apakah pandai:" + isPandai);
        System.out.println("Jenis kelamin:" + kelamin);
        System.out.println("Umur saya saat ini:" + umurSaatIni);
        System.out.println(String.format("Saya ber-ipk %s, dengan tinggi badan %s", $ipk, tinggi ));
    }
}